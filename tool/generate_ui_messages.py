"""Regenerate the offline Flutter UI catalog after editing app_en.arb."""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[1]
messages = json.loads((root / 'lib/l10n/app_en.arb').read_text(encoding='utf-8'))
messages = {key: value for key, value in messages.items() if not key.startswith('@')}
def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
content = '// Generated by tool/generate_ui_messages.py; edit lib/l10n/app_en.arb.\nconst uiMessages = <String, String>{\n'
content += ''.join(f'  {dart(key)}: {dart(value)},\n' for key, value in messages.items())
content += '};\n'
(root / 'lib/core/localization/ui_messages.g.dart').write_text(content, encoding='utf-8')
